  const themeToggle = document.getElementById("themeToggle");
  function setTheme(theme) {
    document.body.classList.toggle("dark", theme === "dark");
    const isDark = theme === "dark";
    themeToggle.setAttribute("aria-label", isDark ? "Switch to light theme" : "Switch to dark theme");
    themeToggle.title = isDark ? "Switch to light theme" : "Switch to dark theme";
    try {
      localStorage.setItem("studyBloomTheme", theme);
    } catch (error) {
      console.warn("Theme preference could not be saved.", error);
    }
  }
  let savedTheme = "light";
  try {
    savedTheme = localStorage.getItem("studyBloomTheme") || "light";
  } catch (error) {
    console.warn("Saved theme preference could not be read.", error);
  }
  setTheme(savedTheme);
  themeToggle.addEventListener("click", () => setTheme(document.body.classList.contains("dark") ? "light" : "dark"));

  function updateReadingProgress() {
    const rect = notesContainer.getBoundingClientRect();
    const fullHeight = Math.max(1, notesContainer.offsetHeight - window.innerHeight * 0.65);
    const passed = Math.max(0, Math.min(fullHeight, -rect.top + 95));
    const progress = notesContainer.children.length ? Math.round((passed / fullHeight) * 100) : 0;
    document.getElementById("progressBar").style.width = `${progress}%`;
    document.getElementById("progressPercent").textContent = `${progress}%`;
    document.getElementById("progressCaption").textContent = progress === 100 ? "Chapter notes reviewed." : "A little review goes a long way.";
    document.getElementById("backToTop").classList.toggle("visible", window.scrollY > 420);
  }
  window.addEventListener("scroll", updateReadingProgress, { passive: true });
  window.addEventListener("resize", updateReadingProgress);
  updateReadingProgress();
  document.getElementById("backToTop").addEventListener("click", () => window.scrollTo({ top: 0, behavior: "smooth" }));
  document.addEventListener("keydown", (event) => {
    if (event.key === "/" && !["INPUT", "TEXTAREA"].includes(document.activeElement.tagName)) {
      event.preventDefault();
      searchInput.focus();
    }
    if (event.key === "Escape" && document.activeElement === searchInput) {
      searchInput.value = "";
      renderNotes();
      searchInput.blur();
    }
  });
